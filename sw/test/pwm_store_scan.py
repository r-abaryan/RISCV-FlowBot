#!/usr/bin/env python3
"""C4 static PWM-write allowlist scan (M2 Stage C4, test only, no firmware change).

Decodes the ROM hex image actually loaded by the simulation (RV32IM, no
compressed ISA), walks every instruction reachable from address 0 and runs a
forward constant propagation over the 32 integer registers (lattice: exact
32-bit constant or UNKNOWN). Calls (jal rd!=x0) and returns (jalr) are handled
context-insensitively: a return flows to every call-return site, and a callee
entry receives the join of all call states. Loads always produce UNKNOWN.

Every store (sb/sh/sw) is classified by its effective address:
  PWM      : address constant and inside the soc_pwm window 0x5000_0200..02FF
  OTHER    : address constant and outside the window
  UNRESOLVED: base register UNKNOWN at that point (could reach the PWM)

A store is reported with the nearest preceding ELF label + offset ("anchor").
The check passes only if
  * the set of PWM stores, as (anchor-label, register-offset) pairs, equals the
    allowlist for that image exactly (no extra site, no missing site), and
  * there is no UNRESOLVED store at all (fail closed, no base-register
    exemption: a store through an unknown sp is rejected like any other), and
  * every store that can reach the PWM window is a 32-bit sw to a word-aligned
    address. sb/sh into the window are rejected. This is a firmware-IMAGE
    verification rule only, not a hardware memory protection: the bus passes
    m_sel_i to soc_pwm and nothing in hardware stops a narrow store.
The PWM window 0x5000_0200..0x5000_02FF is not just assumed: it is re-derived
from the is_periph / is_pwm decode in rtl/bus/soc_interconnect.v on every run,
and the scan fails if they disagree.
Provenance (see fw_provenance.py) is checked before each image is scanned:
robot_nav/soc_cosim ELF==BIN==HEX (+ source rebuild), firmware.hex
regenerated by assemble.py, conv_test.hex regenerated via its ELF/BIN. Missing
prerequisites give rc=2 (never a pass). Nothing tracked is written.
Labels come from the ELF symbol table (riscv-none-elf-nm), the instruction
words from the hex file, so a stale hex or ELF shows up as a mismatch.

Limits (documented, not hidden): this is a static scan of the shipped image
only. It cannot see self-modifying code, code executed from RAM, a corrupted
ROM, or IRQ handlers (none exist: PicoRV32 IRQs are disabled in soc_top). It
is NOT a hardware enforcement: PicoRV32 has no MPU, any store can reach the
PWM. The real protection remains the RTL interlocks (KILL, stale, range,
WDT, E-stop).

Usage: pwm_store_scan.py [--image NAME]... [--list]
Exit 0 = all selected images match, 1 = mismatch, 2 = tool/setup error.
"""
