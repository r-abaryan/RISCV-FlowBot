def pwm_window_from_rtl(path=INTERCONNECT):
    """Derive the PWM slave window from the address decode in the RTL."""
    try:
        src = open(path).read()
    except OSError as e:
        fail(f'cannot read {path}: {e}', 2)
    mp = re.search(r"wire\s+is_periph\s*=\s*\(m_adr_i\[31:24\]\s*==\s*8'h([0-9a-fA-F]+)\)", src)
    mw = re.search(r"wire\s+is_pwm\s*=\s*is_periph\s*&&\s*\(m_adr_i\[23:8\]\s*==\s*16'h([0-9a-fA-F]+)\)", src)
    if not (mp and mw):
        fail(f'is_periph/is_pwm decode not found in {path}: cannot verify PWM window', 2)
    lo = (int(mp.group(1), 16) << 24) | (int(mw.group(1), 16) << 8)
    return lo, lo | 0xFF

REG = ['zero', 'ra', 'sp', 'gp', 'tp', 't0', 't1', 't2', 's0', 's1', 'a0', 'a1',
       'a2', 'a3', 'a4', 'a5', 'a6', 'a7', 's2', 's3', 's4', 's5', 's6', 's7',
       's8', 's9', 's10', 's11', 't3', 't4', 't5', 't6']
U = None  # UNKNOWN
M32 = 0xFFFFFFFF


def fail(msg, rc=1):
    print('PWM-SCAN-FAIL: ' + msg)
    sys.exit(rc)


def sx(v, bits):
    v &= (1 << bits) - 1
    return v - (1 << bits) if v >> (bits - 1) else v


def decode(w):
    op = w & 0x7F
    rd = (w >> 7) & 31; f3 = (w >> 12) & 7; rs1 = (w >> 15) & 31
    rs2 = (w >> 20) & 31; f7 = w >> 25
    i_imm = sx(w >> 20, 12)
    s_imm = sx(((w >> 25) << 5) | ((w >> 7) & 31), 12)
    b_imm = sx((((w >> 31) & 1) << 12) | (((w >> 7) & 1) << 11) |
               (((w >> 25) & 0x3F) << 5) | (((w >> 8) & 0xF) << 1), 13)
    j_imm = sx((((w >> 31) & 1) << 20) | (((w >> 12) & 0xFF) << 12) |
               (((w >> 20) & 1) << 11) | (((w >> 21) & 0x3FF) << 1), 21)
    return dict(op=op, rd=rd, f3=f3, rs1=rs1, rs2=rs2, f7=f7, i=i_imm,
                s=s_imm, b=b_imm, j=j_imm, u=w & 0xFFFFF000)


def alu(f3, f7, a, b, is_imm):
    if a is U or b is U:
        return U
    sh = b & 31
    if f7 == 1 and not is_imm:  # M extension
        sa, sb_ = sx(a, 32), sx(b, 32)
        if f3 == 0: return (a * b) & M32
        if f3 == 1: return ((sa * sb_) >> 32) & M32
        if f3 == 2: return ((sa * b) >> 32) & M32
        if f3 == 3: return ((a * b) >> 32) & M32
        return U  # div/rem: not needed for addresses
    if f3 == 0:
        return (a - b) & M32 if (f7 == 0x20 and not is_imm) else (a + b) & M32
    if f3 == 1: return (a << sh) & M32
    if f3 == 2: return int(sx(a, 32) < sx(b, 32))
    if f3 == 3: return int(a < b)
    if f3 == 4: return a ^ b
    if f3 == 5:
        return (sx(a, 32) >> sh) & M32 if f7 == 0x20 else a >> sh
    if f3 == 6: return a | b
    if f3 == 7: return a & b


def join(s1, s2):
    return tuple(x if x == y else U for x, y in zip(s1, s2))


def load_words(hexf):
    words = []
    for ln, line in enumerate(open(hexf), 1):
        t = line.strip()
        if len(t) != 8:
            fail(f'{hexf}:{ln} not an 8-digit word', 2)
        words.append(int(t, 16))
    return words


def load_labels(elf):
    try:
        out = subprocess.run(['riscv-none-elf-nm', '-n', elf], check=True,
                             capture_output=True, text=True).stdout
    except (OSError, subprocess.CalledProcessError) as e:
        fail(f'nm failed on {elf}: {e}', 2)
    labs = []
    for line in out.splitlines():
        p = line.split()
        if len(p) == 3 and p[1] in 'tT':
            labs.append((int(p[0], 16), p[2]))
    return sorted(labs)


def anchor(labs, pc):
    best = None
    for a, n in labs:
        if a <= pc:
            best = (a, n)
    return best


MAX_STATES = 300000
WIDEN_AFTER = 64   # distinct values; > largest constant-trip loop (33)
# Per-image tracking bound. conv_test_firmware.s runs one constant-trip loop of
# 512 iterations (v = -256..255, out pointer 0x2000_1000 + 4*i); with 64 the
# pointer widens to UNKNOWN and its RAM store is (correctly) UNRESOLVED.
# 600 > 512 keeps it exact. This is a precision setting, not an exemption:
# any widened store still fails closed.
IMAGE_WIDEN = {'conv_test': 600}
# Negative-control hooks only (NC8 state cap, NC9 tracking bound). Announced
# loudly; the gate never sets them.
OVERRIDES = []
if os.environ.get('PWM_SCAN_MAX_STATES'):
    MAX_STATES = int(os.environ['PWM_SCAN_MAX_STATES']); OVERRIDES.append(f'MAX_STATES={MAX_STATES}')
if os.environ.get('PWM_SCAN_WIDEN_AFTER'):
    WIDEN_AFTER = int(os.environ['PWM_SCAN_WIDEN_AFTER']); OVERRIDES.append(f'WIDEN_AFTER={WIDEN_AFTER}')
RAM_LO, RAM_HI = 0x20000000, 0x20003FFF


def br_taken(f3, a, b):
    if a is U or b is U:
        return None
    if f3 == 0: return a == b
    if f3 == 1: return a != b
    if f3 == 4: return sx(a, 32) < sx(b, 32)
    if f3 == 5: return sx(a, 32) >= sx(b, 32)
    if f3 == 6: return a < b
    if f3 == 7: return a >= b
    return None


def uses_defs(d):
    op = d['op']; r1, r2, rd = d['rs1'], d['rs2'], d['rd']
    if op in (0x37, 0x17, 0x6F): return set(), {rd}
    if op in (0x13, 0x03): return {r1}, {rd}
    if op == 0x67: return {r1}, {rd}
    if op == 0x33: return {r1, r2}, {rd}
    if op in (0x23, 0x63): return {r1, r2}, set()
    return set(), set()


def liveness(words):
    """Conservative register liveness on the static supergraph: branches take
    both edges, jal ra goes to the callee, a ret flows to every call-return
    site. Over-approximating liveness is sound for the projection below."""
    n = len(words)
    dec = [decode(w) for w in words]
    rets = [4 * i + 4 for i, d in enumerate(dec) if d['op'] == 0x6F and d['rd'] == 1]
    succ = []
    for i, d in enumerate(dec):
        pc = 4 * i; op = d['op']
        if op == 0x63: sc = [pc + 4, pc + d['b']]
        elif op == 0x6F: sc = [pc + d['j']]
        elif op == 0x67: sc = rets
        elif op == 0x73: sc = []
        else: sc = [pc + 4]
        succ.append([q // 4 for q in sc if q % 4 == 0 and 0 <= q // 4 < n])
    live = [set() for _ in range(n)]
    changed = True
    while changed:
        changed = False
        for i in range(n - 1, -1, -1):
            u, df = uses_defs(dec[i])
            out = set()
            for j in succ[i]:
                out |= live[j]
            new = (out - df) | u
            new.discard(0)
            if new != live[i]:
                live[i] = new; changed = True
    return live


def scan(words, widen=None):
    WIDEN_AFTER = widen if widen is not None else globals()['WIDEN_AFTER']
    """Path-sensitive abstract execution over exact 32-bit constants.
    State = (pc, call stack, registers, tracked RAM words). Registers are an
    exact constant or UNKNOWN (loads from untracked memory, CSR-free code).
    Registers that are dead at a pc (liveness) are forced to UNKNOWN, which is
    sound and collapses equivalent states. Branches with known operands take
    one edge; otherwise both. Identical states are explored once, so loops
    with constant trip counts are unrolled exactly and polling loops stop when
    the state repeats. Calls push the return address; the only accepted jalr
    is a plain ret whose ra equals the top of the call stack."""
    n = len(words)
    live = liveness(words)
    def proj(pc, regs):
        lv = live[pc // 4] if 0 <= pc // 4 < n else set()
        return tuple(v if (i == 0 or i in lv) else U for i, v in enumerate(regs))
    start = (0, (), proj(0, [0] + [U] * 31), ())
    seen = {start}
    wid = {}
    work = [start]
    stores = {}
    reach = set()
    bad = set()
    while work:
        if len(seen) > MAX_STATES:
            bad.add(f'state explosion (> {MAX_STATES} states): scan incomplete')
            break
        pc, stk, regs, mem = work.pop()
        reach.add(pc)
        st = list(regs)
        memd = dict(mem)
        d = decode(words[pc // 4])
        op = d['op']
        nxt = [pc + 4]
        nstk = stk
        def wr(r, v):
            if r:
                st[r] = v
        if op == 0x37: wr(d['rd'], d['u'])
        elif op == 0x17: wr(d['rd'], (pc + d['u']) & M32)
        elif op == 0x13:
            f7 = d['f7'] if d['f3'] == 5 else 0
            wr(d['rd'], alu(d['f3'], f7, st[d['rs1']], d['i'] & M32, True))
        elif op == 0x33:
            wr(d['rd'], alu(d['f3'], d['f7'], st[d['rs1']], st[d['rs2']], False))
        elif op == 0x03:
            b = st[d['rs1']]
            a = U if b is U else (b + d['i']) & M32
            wr(d['rd'], memd.get(a, U) if (d['f3'] == 2 and a is not U) else U)
        elif op == 0x23:
            b = st[d['rs1']]
            a = U if b is U else (b + d['s']) & M32
            stores.setdefault(pc, set()).add(a)
            if a is U:
                memd = {}  # may alias any tracked word
            elif RAM_LO <= a <= RAM_HI:
                if d['f3'] == 2 and a % 4 == 0 and st[d['rs2']] is not U:
                    memd[a] = st[d['rs2']]
                else:
                    memd.pop(a & ~3, None)
        elif op == 0x63:
            t = br_taken(d['f3'], st[d['rs1']], st[d['rs2']])
            nxt = [pc + 4, pc + d['b']] if t is None else [pc + d['b'] if t else pc + 4]
        elif op == 0x6F:
            if d['rd'] == 1:
                nstk = stk + (pc + 4,)
                if len(nstk) > 8:
                    bad.add(f'call depth > 8 at 0x{pc:x} (recursion?)'); continue
            elif d['rd'] != 0:
                bad.add(f'jal with link register {REG[d["rd"]]} at 0x{pc:x}'); continue
            wr(d['rd'], pc + 4)
            nxt = [pc + d['j']]
        elif op == 0x67:
            tg = st[1]
            if not (d['rd'] == 0 and d['rs1'] == 1 and d['i'] == 0 and stk and tg == stk[-1]):
                bad.add(f'unverifiable jalr at 0x{pc:x} (ra={"?" if tg is U else hex(tg)}, '
                        f'expected {hex(stk[-1]) if stk else "no caller"})')
                continue
            nxt = [stk[-1]]; nstk = stk[:-1]
        elif op == 0x0F: pass
        elif op == 0x73:
            bad.add(f'SYSTEM instruction at 0x{pc:x}'); continue
        else:
            bad.add(f'undecodable word 0x{words[pc//4]:08x} at reachable 0x{pc:x}')
            continue
        m_ = tuple(sorted(memd.items()))
        for q in nxt:
            if q % 4 or not 0 <= q // 4 < n:
                bad.add(f'control flow leaves ROM image at 0x{q:x}'); continue
            pr, mm = list(proj(q, st)), m_
            key = (q, nstk)
            vr = wid.setdefault(key, {})
            # widening (sound): a register or tracked RAM word that has taken
            # more than WIDEN_AFTER distinct values at this (pc, call stack)
            # becomes UNKNOWN there, so loops walking loaded data terminate
            for i in range(1, 32):
                if pr[i] is not U:
                    vals = vr.setdefault(i, set())
                    if vals is U or (pr[i] not in vals and len(vals) >= WIDEN_AFTER):
                        vr[i] = U; pr[i] = U
                    else:
                        vals.add(pr[i])
            keep = []
            for k_, v_ in mm:
                vals = vr.setdefault(('m', k_), set())
                if vals is U or (v_ not in vals and len(vals) >= WIDEN_AFTER):
                    vr[('m', k_)] = U
                else:
                    vals.add(v_); keep.append((k_, v_))
            pr, mm = tuple(pr), tuple(keep)
            s_ = (q, nstk, pr, mm)
            if s_ not in seen:
                seen.add(s_); work.append(s_)
    final = {}
    for pc, addrs in stores.items():
        d = decode(words[pc // 4])
        final[pc] = (d['f3'], REG[d['rs1']], d['s'], REG[d['rs2']], addrs)
    return final, sorted(bad), (len(reach), len(seen))


def check(name, hexf, elf, listing):
    words = load_words(hexf)
    labs = load_labels(elf)
    wa = WIDEN_AFTER if 'WIDEN_AFTER' in ' '.join(OVERRIDES) else IMAGE_WIDEN.get(name, WIDEN_AFTER)
    stores, bad, nreach = scan(words, wa)
    pwm, unres, narrow, other = set(), [], [], 0
    rows = []
    for pc in sorted(stores):
        f3, rb, off, rs, addrs = stores[pc]
        a = anchor(labs, pc)
        lab = a[1] if a else '?'
        if U in addrs:
            cls = 'UNRESOLVED'
            unres.append(pc)  # fail closed, whatever the base register
        elif any(PWM_LO <= x <= PWM_HI for x in addrs):
            cls = 'PWM'
            if f3 != 2 or any(x & 3 for x in addrs):
                narrow.append((pc, f3))
            if len(addrs) != 1:
                unres.append(pc)  # one site, several PWM targets: not allowed
            for x in addrs:
                if PWM_LO <= x <= PWM_HI:
                    pwm.add((lab, x - PWM_LO, rs))
        else:
            cls = 'OTHER'; other += 1
        shown = ','.join('?' if x is U else hex(x) for x in sorted(addrs, key=lambda v: -1 if v is U else v)[:3])
        if len(addrs) > 3: shown += f',...({len(addrs)})'
        rows.append(f'  0x{pc:04x} {lab}+0x{pc - a[0]:x} s{"bhw"[f3] if f3 < 3 else "?"} '
                    f'{rs},{off}({rb}) -> {shown} {cls}')
    if listing:
        print(f'[{name}] reachable instructions: {nreach[0]}, explored states: {nreach[1]}')
        print('\n'.join(rows))
    ok = True
    for b in bad:
        print(f'[{name}] {b}'); ok = False
    for pc in unres:
        print(f'[{name}] UNRESOLVED store base at 0x{pc:x} (could reach PWM)'); ok = False
    for pc, f3 in narrow:
        print(f'[{name}] narrow/unaligned PWM store at 0x{pc:x} '
              f'(s{"bhw?"[min(f3, 3)]}; only aligned sw allowed)'); ok = False
    allow = ALLOW[name]
    extra, missing = pwm - allow, allow - pwm
    for e in sorted(extra):
        print(f'[{name}] PWM store NOT in allowlist: {e}'); ok = False
    for m in sorted(missing):
        print(f'[{name}] allowlisted PWM store missing: {m}'); ok = False
    print(f'[{name}] PWM stores {len(pwm)} (allowlist {len(allow)}), other {other}, '
          f'unresolved {len(unres)}, narrow {len(narrow)}, reachable {nreach[0]}, '
          f'states {nreach[1]}, widen {wa} -> {"PASS" if ok else "FAIL"}')
    return ok


def main():
    global PWM_LO, PWM_HI
    import fw_provenance as FP
    args = sys.argv[1:]
    listing = '--list' in args
    names = [args[i + 1] for i, a in enumerate(args) if a == '--image'] or list(IMAGES)
    for nm in names:
        if nm not in IMAGES:
            fail(f'unknown image {nm}', 2)
    hexov = os.environ.get('PWM_SCAN_HEX')  # negative-control hook: replace hex
    if hexov and len(names) != 1:
        fail('PWM_SCAN_HEX needs exactly one --image', 2)
    if OVERRIDES:
        print(f'[PWM-SCAN] NEGATIVE-CONTROL OVERRIDES ACTIVE: {", ".join(OVERRIDES)}')
    lo, hi = pwm_window_from_rtl()
    if (lo, hi) != (PWM_LO, PWM_HI):
        fail(f'PWM window in soc_interconnect.v 0x{lo:08x}..0x{hi:08x} != scanner '
             f'0x{PWM_LO:08x}..0x{PWM_HI:08x}', 1)
    print(f'[PWM-SCAN] PWM window 0x{lo:08x}..0x{hi:08x} matches rtl/bus/soc_interconnect.v')
    ok = True
    with tempfile.TemporaryDirectory(prefix='pwmscan_') as td:
        try:
            FP.check_tools()
        except FP.ProvenanceError as e:
            fail(str(e), e.rc)
        for nm in names:
            hexf = os.path.join(FW, IMAGES[nm][0])
            try:
                # provenance of the TRACKED hex is skipped only when a
                # negative control substitutes a mutated copy
                elf = FP.prepare(nm, td, check=not hexov)
            except FP.ProvenanceError as e:
                fail(f'provenance {nm}: {e}', e.rc)
            if hexov:
                hexf = hexov
            if not os.path.exists(hexf):
                fail(f'{hexf} missing', 2)
            ok &= check(nm, hexf, elf, listing)
    print('[PWM-SCAN-PASS]' if ok else '[PWM-SCAN-FAIL]')
    sys.exit(0 if ok else 1)


if __name__ == '__main__':
    main()
