#!/usr/bin/env python3
"""
Weight Exporter for rv_nna RISC-V Neural Accelerator
Packs Layer 1 and Layer 2 weights, biases, and test inputs into RISC-V assembly and C header format.
Supports exporting either default handcrafted weights or trained policy weights (JSON).
"""

import os
import sys
import json

def pack_int8_to_words(int8_list):
    """Packs a list of INT8 into 32-bit little-endian words."""
    words = []
    # Pad to multiple of 4
    padded = list(int8_list)
    while len(padded) % 4 != 0:
        padded.append(0)
    for i in range(0, len(padded), 4):
        b0 = padded[i] & 0xFF
        b1 = padded[i+1] & 0xFF
        b2 = padded[i+2] & 0xFF
        b3 = padded[i+3] & 0xFF
        word = (b3 << 24) | (b2 << 16) | (b1 << 8) | b0
        words.append(word)
    return words

def pack_weights_matrix(matrix):
    """
    Packs an M x K weight matrix into memory words.
    In rv_nna, row m starts at m * ceil(K/4) words.
    """
    words = []
    for row in matrix:
        words.extend(pack_int8_to_words(row))
    return words

def load_weights(trained_json=None):
    if trained_json and os.path.exists(trained_json):
        with open(trained_json) as f:
            d = json.load(f)
        return (d["l1"]["weights"], d["l1"]["biases"], d["l1"]["scale_mult"], d["l1"]["scale_shift"],
                d["l2"]["weights"], d["l2"]["biases"], d["l2"]["scale_mult"], d["l2"]["scale_shift"])
    else:
        from nav_policy import L1_WEIGHTS, L1_BIAS, L1_SCALE_MULT, L1_SCALE_SHIFT
        from nav_policy import L2_WEIGHTS, L2_BIAS, L2_SCALE_MULT, L2_SCALE_SHIFT
        return (L1_WEIGHTS, L1_BIAS, L1_SCALE_MULT, L1_SCALE_SHIFT,
                L2_WEIGHTS, L2_BIAS, L2_SCALE_MULT, L2_SCALE_SHIFT)

def generate_asm_include(filepath, l1_w, l1_b, l1_mult, l1_shift, l2_w, l2_b, l2_mult, l2_shift):
    l1_w_words = pack_weights_matrix(l1_w)
    l1_b_words = [b & 0xFFFFFFFF for b in l1_b]
    
    l2_w_words = pack_weights_matrix(l2_w)
    l2_b_words = [b & 0xFFFFFFFF for b in l2_b]

    with open(filepath, "w") as f:
        f.write("/* Auto-generated by export_weights.py - Do not edit manually */\n\n")
        f.write("    .section .rodata\n")
        f.write("    .globl l1_weights, l1_biases, l2_weights, l2_biases\n\n")

        # Layer 1
        f.write(f"/* Layer 1: K={len(l1_w[0])}, M={len(l1_w)}, ScaleMult={l1_mult}, ScaleShift={l1_shift} */\n")
        f.write("    .balign 4\n")
        f.write("l1_weights:\n")
        for i, w in enumerate(l1_w_words):
            f.write(f"    .word 0x{w:08x}  /* W1[{i}] */\n")
        f.write("\n    .balign 4\n")
        f.write("l1_biases:\n")
        for i, b in enumerate(l1_b_words):
            f.write(f"    .word 0x{b:08x}  /* B1[{i}] */\n")

        # Layer 2
        f.write(f"\n/* Layer 2: K={len(l2_w[0])}, M={len(l2_w)}, ScaleMult={l2_mult}, ScaleShift={l2_shift} */\n")
        f.write("    .balign 4\n")
        f.write("l2_weights:\n")
        for i, w in enumerate(l2_w_words):
            f.write(f"    .word 0x{w:08x}  /* W2[{i}] */\n")
        f.write("\n    .balign 4\n")
        f.write("l2_biases:\n")
        for i, b in enumerate(l2_b_words):
            f.write(f"    .word 0x{b:08x}  /* B2[{i}] */\n")

        f.write("\n")
    print(f"Generated {filepath}")

def generate_c_header(filepath, l1_w, l1_b, l1_mult, l1_shift, l2_w, l2_b, l2_mult, l2_shift):
    l1_w_words = pack_weights_matrix(l1_w)
    l1_b_words = [b & 0xFFFFFFFF for b in l1_b]
    l2_w_words = pack_weights_matrix(l2_w)
    l2_b_words = [b & 0xFFFFFFFF for b in l2_b]

    with open(filepath, "w") as f:
        f.write("/* Auto-generated by export_weights.py */\n")
        f.write("#ifndef NAV_WEIGHTS_H\n#define NAV_WEIGHTS_H\n\n")
        f.write("#include <stdint.h>\n\n")
        f.write(f"#define L1_K {len(l1_w[0])}\n")
        f.write(f"#define L1_M {len(l1_w)}\n")
        f.write(f"#define L1_SCALE_MULT {l1_mult}\n")
        f.write(f"#define L1_SCALE_SHIFT {l1_shift}\n\n")
        
        f.write(f"#define L2_K {len(l2_w[0])}\n")
        f.write(f"#define L2_M {len(l2_w)}\n")
        f.write(f"#define L2_SCALE_MULT {l2_mult}\n")
        f.write(f"#define L2_SCALE_SHIFT {l2_shift}\n\n")

        f.write("static const uint32_t l1_weights[] = {\n")
        for w in l1_w_words:
            f.write(f"    0x{w:08x}U,\n")
        f.write("};\n\n")

        f.write("static const uint32_t l1_biases[] = {\n")
        for b in l1_b_words:
            f.write(f"    0x{b:08x}U,\n")
        f.write("};\n\n")

        f.write("static const uint32_t l2_weights[] = {\n")
        for w in l2_w_words:
            f.write(f"    0x{w:08x}U,\n")
        f.write("};\n\n")

        f.write("static const uint32_t l2_biases[] = {\n")
        for b in l2_b_words:
            f.write(f"    0x{b:08x}U,\n")
        f.write("};\n\n")

        f.write("#endif /* NAV_WEIGHTS_H */\n")
    print(f"Generated {filepath}")

if __name__ == "__main__":
    trained_file = "sw/policy/trained_policy_weights.json" if "--trained" in sys.argv else None
    weights = load_weights(trained_file)
    generate_asm_include("sw/firmware/nav_weights.inc", *weights)
    generate_c_header("sw/include/nav_weights.h", *weights)
