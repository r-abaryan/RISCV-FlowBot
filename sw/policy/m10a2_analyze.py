"""Summarise results/m10a2/trace.json -> results/m10a2/summary.md (stats over logged steps only)."""
import json, sys, os, collections, statistics as S
H = os.path.dirname(os.path.abspath(__file__)); R = os.path.join(H, "../../results/m10a2")
rec = json.load(open(os.path.join(R, "trace.json")))
L = []
def p(s=""): L.append(s)
def stats(steps):
    n = len(steps)
    if not n: return None
    c = collections.Counter(s["why"] for s in steps)
    return n, c
p("# M10a-2 trace summary (generated by m10a2_analyze.py)\n")
p(f"Episodes: {len(rec)} stalled filtered 150-step timeouts (first 4 per policy/env cell). All outcome-identical to M10a: {all(r['identical'] for r in rec)}\n")
p("## Per-episode (last 50 steps = stall window)\n")
p("| policy | env | seed | dfin (m) | NORMAL | DYN_TTC | CRIT_BRAKE | med v_req | med v_perm | med min_hit (m) | d_margin | max stall_run | steps v_req>0.1 and v_perm<0.02 |")
p("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
agg_all = collections.Counter(); agg_win = collections.Counter(); blocked = 0; wintot = 0; win_steps = []
onset = collections.Counter(); crit_hit_below = 0; crit_total = 0
for r in rec:
    lg = r["log"]; w = lg[-50:]; win_steps += w
    c = collections.Counter(s["why"] for s in w)
    agg_win += c; agg_all += collections.Counter(s["why"] for s in lg)
    b = sum(1 for s in w if s["v_req"] > 0.1 and s["v_perm"] < 0.02); blocked += b; wintot += len(w)
    p(f"| {r['policy']} | {r['env']} | {r['seed']} | {r['result']['dfin']:.2f} | {c['NORMAL']} | {c['DYNAMIC_TTC_BRAKING']} | {c['CRITICAL_OBSTACLE_BRAKE']} | "
      f"{S.median(s['v_req'] for s in w):.3f} | {S.median(s['v_perm'] for s in w):.3f} | {S.median(s['min_hit'] for s in w):.3f} | {w[0]['d_margin']:.3f} | "
      f"{max(s['stall_run'] for s in lg)} | {b} |")
    # stall onset: first step where stall_run reaches 10; reason at that step
    for s in lg:
        if s["stall_run"] >= 10: onset[s["why"]] += 1; break
p("\n## Aggregate\n")
tot_w = sum(agg_win.values()); tot_a = sum(agg_all.values())
p("| reason | all logged steps | last-50 window steps |"); p("|---|---|---|")
for k in ["NORMAL", "DYNAMIC_TTC_BRAKING", "CRITICAL_OBSTACLE_BRAKE"]:
    p(f"| {k} | {agg_all[k]} ({100*agg_all[k]/tot_a:.1f} percent) | {agg_win[k]} ({100*agg_win[k]/tot_w:.1f} percent) |")
p(f"\nWindow steps where policy asked v_req>0.1 but permitted v<0.02: {blocked} of {wintot} ({100*blocked/wintot:.1f} percent).")
p(f"Reason at the step where each episode's consecutive-stall counter first reached 10: {dict(onset)} (episodes without such a step are omitted).")
# in window, mean angular req vs perm, and goal-distance change
dg = [s["d_goal_delta"] for s in win_steps]
p(f"Window mean d_goal change per step: {S.mean(dg):+.5f} m (negative = approaching); mean |w_perm|: {S.mean(abs(s['w_perm']) for s in win_steps):.3f} rad/s; mean |w_req|: {S.mean(abs(s['w_req']) for s in win_steps):.3f} rad/s.")
cb = [s for s in win_steps if s["why"] == "CRITICAL_OBSTACLE_BRAKE"]
if cb: p(f"CRITICAL steps in window: median min_hit {S.median(s['min_hit'] for s in cb):.3f} m (d_margin {cb[0]['d_margin']:.3f}); median v_req {S.median(s['v_req'] for s in cb):.3f}; fraction with |w_perm|>0.1: {sum(abs(s['w_perm'])>0.1 for s in cb)/len(cb):.2f}.")
# NORMAL-but-stalled
nm = [s for s in win_steps if s["why"] == "NORMAL"]
if nm: p(f"NORMAL steps in window: median v_req {S.median(s['v_req'] for s in nm):.3f}, median v_perm {S.median(s['v_perm'] for s in nm):.3f}, median min_hit {S.median(s['min_hit'] for s in nm):.3f}.")
rays = collections.Counter(s["min_ray"] for s in cb)
p("Closest ray index among CRITICAL window steps (0..7 = -90,-60,-30,-10,+10,+30,+60,+90 deg): " + str(dict(sorted(rays.items()))) + f"; side rays (0 or 7) = {100*(rays[0]+rays[7])/max(1,len(cb)):.1f} percent.")
open(os.path.join(R, "summary.md"), "w").write("\n".join(L) + "\n"); print("\n".join(L))
